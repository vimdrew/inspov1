/**
 * Suggests an outfit name ("Midnight Mirage") so adding an outfit never stalls
 * on naming it. Purely cosmetic, so duplicates are fine.
 */
export const randomOutfitName = (): string => {
  const pick = <T>(items: readonly T[]) => items[Math.floor(Math.random() * items.length)];
  return `${pick(ADJECTIVES)} ${pick(NOUNS)}`;
};
